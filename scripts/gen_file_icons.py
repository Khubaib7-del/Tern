#!/usr/bin/env python3
"""Builds Tern's file-type logos and their lookup table.

    python3 scripts/gen_file_icons.py [--src DIR]

--src DIR   a folder of the approved 256x256 PNGs (named as in the
            catalogue's `file` column). Each is downscaled to 64x64 (256-colour
            palette with alpha) into
            crates/tern-desktop/assets/file-icons/. Without --src the
            committed 64 px PNGs are used as they are.

Reads crates/tern-desktop/assets/file-icons/catalog.csv
(category,type,extensions,icon,file) and writes
crates/tern-desktop/src/fileicon_table.rs. Needs Pillow.

Catalogue rules: extensions are space-separated and matched without case.
An entry starting with "." or with a capital letter (".gitignore",
"Dockerfile", "CMakeLists.txt") is a whole file name; any other entry is
a suffix after a dot ("component.ts" matches "app.component.ts"). The
"(anything else)" row is the fallback. An extension two rows claim must
be settled in PICK, or the script stops.
"""

import argparse
import csv
import os
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ASSETS = os.path.join(ROOT, "crates/tern-desktop/assets/file-icons")
CATALOG = os.path.join(ASSETS, "catalog.csv")
OUT = os.path.join(ROOT, "crates/tern-desktop/src/fileicon_table.rs")
SIZE = 64

# Extensions more than one row claims: the row (type) that wins.
PICK = {
    "m": "MATLAB",
    "v": "Verilog",
    "bas": "Visual Basic",
    "nc": "HDF5 / NetCDF",
    "key": "Apple Keynote",
    "pro": "Prolog",
    "cls": "LaTeX",
    "d": "D",
    "obj": "3D model",
    "vhd": "VHDL",
}
# Logos drawn (nearly) all in black or dark grey: they sit on a light
# tile on a dark page. Found by measuring the pixels, plus these named.
DARK_FORCED = {"rust", "yaml", "cobol", "solidity", "torrent", "markdown", "json"}
DARK_SHARE = 0.3


def stem(file_col):
    return os.path.splitext(os.path.basename(file_col))[0]


def is_dark(path):
    im = Image.open(path).convert("RGBA")
    px = [p for p in im.getdata() if p[3] > 128]
    if not px:
        return False
    dark = sum(1 for r, g, b, _ in px if max(r, g, b) < 110 and max(r, g, b) - min(r, g, b) < 40)
    return dark / len(px) >= DARK_SHARE


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src")
    args = ap.parse_args()
    rows = list(csv.DictReader(open(CATALOG, newline="", encoding="utf-8")))
    icons = []  # (stem, type)
    index = {}
    for r in rows:
        s = stem(r["file"])
        if s not in index:
            index[s] = len(icons)
            icons.append((s, r["type"]))
    if args.src:
        os.makedirs(ASSETS, exist_ok=True)
        for s, _ in icons:
            im = Image.open(os.path.join(args.src, s + ".png")).convert("RGBA")
            im = im.resize((SIZE, SIZE), Image.LANCZOS)
            # A 256-colour palette with alpha: half the bytes, same look.
            im = im.quantize(256, method=Image.Quantize.FASTOCTREE)
            im.save(os.path.join(ASSETS, s + ".png"), optimize=True)
    names, exts, claims = {}, {}, {}
    fallback = None
    for r in rows:
        i = index[stem(r["file"])]
        for e in r["extensions"].split():
            if e.startswith("("):
                fallback = i
                break
            if e.startswith(".") or e[0].isupper():
                names[e.lower()] = i
            else:
                claims.setdefault(e.lower(), []).append((r["type"], i))
    for e, cs in claims.items():
        if len(cs) == 1:
            exts[e] = cs[0][1]
            continue
        want = PICK.get(e)
        # The pick may also be a row that does not list the extension
        # (.bas -> Visual Basic, over VBA and BASIC).
        hit = [i for t, i in cs if t == want] or [
            index[stem(r["file"])] for r in rows if r["type"] == want
        ]
        if not hit:
            sys.exit(f"extension .{e} is claimed by {[t for t, _ in cs]}: settle it in PICK")
        exts[e] = hit[0]
    if fallback is None:
        sys.exit("no (anything else) row")
    dark = [s in DARK_FORCED or is_dark(os.path.join(ASSETS, s + ".png")) for s, _ in icons]

    q = lambda s: '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'
    out = [
        "// @generated by scripts/gen_file_icons.py from",
        "// assets/file-icons/catalog.csv. Do not edit by hand.",
        "",
        "/// Every logo: (name, what it is, 64 px PNG, drawn in black or dark grey).",
        "pub static ICONS: &[(&str, &str, &[u8], bool)] = &[",
    ]
    for (s, t), d in zip(icons, dark):
        out.append(
            f'    ({q(s)}, {q(t)}, include_bytes!("../assets/file-icons/{s}.png"), {str(d).lower()}),'
        )
    out += [
        "];",
        "",
        "/// Whole file names (lower case) and their logo.",
        "pub static BY_NAME: &[(&str, usize)] = &[",
    ]
    out += [f"    ({q(n)}, {i})," for n, i in sorted(names.items())]
    out += [
        "];",
        "",
        "/// Suffixes after a dot (lower case, sorted) and their logo.",
        "pub static BY_EXT: &[(&str, usize)] = &[",
    ]
    out += [f"    ({q(e)}, {i})," for e, i in sorted(exts.items())]
    out += ["];", "", "/// The logo for anything else.", f"pub const UNKNOWN: usize = {fallback};", ""]
    open(OUT, "w", encoding="utf-8").write("\n".join(out))
    print(f"{len(icons)} logos, {len(names)} names, {len(exts)} suffixes, dark {sum(dark)}: "
          + ", ".join(s for (s, _), d in zip(icons, dark) if d))


if __name__ == "__main__":
    main()
